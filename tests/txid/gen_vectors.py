#!/usr/bin/env python3
"""Regenerates ../../txid_vectors.h from ../../vectors-txid-blake2b.json. Run from tests/txid/."""
import json
v = json.load(open('../../vectors-txid-blake2b.json'))
o = ['// GENERATED by tests/txid/gen_vectors.py from vectors-txid-blake2b.json (Proxima library upgrade 6 test vectors)',
     '// prefix[i] = (i*7+3) & 0xff; the nonce is extranonce1 || extranonce2.', '#pragma once', 'namespace txid {',
     'struct Vector { int prefix_len; unsigned en1; unsigned long long en2; const char *hash; int tz; unsigned long long first_en2; const char *first_hash; int first_tz; };',
     'static const Vector VECTORS[] = {']
for x in v:
    f = x['first_en2_with_tz_ge_12']
    o.append('    {%d, 0x%s, 0x%sULL, "%s", %d, 0x%sULL, "%s", %d},' % (x['prefix_len'], x['extranonce1'], x['extranonce2'], x['hash'], x['trailing_zeros'], f['extranonce2'], f['hash'], f['trailing_zeros']))
o += ['};', 'static const int NVECTORS = sizeof(VECTORS) / sizeof(VECTORS[0]);', '} // namespace txid', '']
open('../../txid_vectors.h', 'w').write('\n'.join(o))
